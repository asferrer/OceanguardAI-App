package com.oceanguard.ai.inference

import com.oceanguard.ai.data.DebrisMaterial
import com.oceanguard.ai.data.DetectionSession
import com.oceanguard.ai.data.HealthTrend
import java.text.SimpleDateFormat
import java.util.Locale

/**
 * Deterministic template-based report builders used as fallback when the
 * VLM is unavailable. Extracted from [ReportGenerator] to keep file sizes
 * manageable.
 */
internal object ReportTemplateBuilder {

    private val DATE_FORMAT = SimpleDateFormat("yyyy-MM-dd HH:mm", Locale.getDefault())
    private val DAY_FORMAT = SimpleDateFormat("yyyy-MM-dd", Locale.getDefault())

    private val LANGUAGE_NAMES = mapOf(
        "en" to "English", "es" to "Spanish", "fr" to "French",
        "de" to "German", "it" to "Italian", "pt" to "Portuguese",
    )

    // -----------------------------------------------------------------
    // Generic (non-zone) template report
    // -----------------------------------------------------------------

    fun buildTemplateReport(
        sessions: List<DetectionSession>,
        language: String,
        audience: ReportAudience = ReportAudience.SCIENTIFIC,
    ): String {
        val totalDebris = sessions.sumOf { it.totalCount }
        val avgHealth = sessions.map { it.healthScore }.average()
        val sessionCount = sessions.size
        val materialMap = buildMaterialMap(sessions)
        val dominantMaterial = materialMap.maxByOrNull { it.value }
        val highRiskCount = countHighRisk(sessions)
        val dateRange = formatDateRange(sessions)
        val healthLabel = healthLabel(avgHealth)

        val materialBreakdownStr = formatMaterialBreakdown(materialMap)
        val locationsWithData = sessions.mapNotNull { it.location }
        val locationNote = if (locationsWithData.isNotEmpty()) {
            "GPS data was recorded for ${locationsWithData.size} of $sessionCount sessions."
        } else {
            "No GPS coordinates were recorded for this survey."
        }

        val dominantMaterialSentence = dominantMaterial?.let { (mat, count) ->
            "The most prevalent debris material was **${mat.name.replace("_", " ")}** ($count items), " +
                "which requires immediate targeted intervention due to its persistence in marine environments."
        } ?: "No single dominant material was identified across the survey sessions."

        val riskSentence = if (highRiskCount > 0) {
            "A total of **$highRiskCount high-risk item(s)** were detected, posing elevated threats " +
                "of entanglement, ingestion, or chemical contamination to marine fauna."
        } else {
            "No high-risk items were identified in this survey period."
        }

        val title = when (audience) {
            ReportAudience.SCIENTIFIC -> "Marine Debris Survey Report"
            ReportAudience.NGO_MANAGER -> "Marine Debris Field Assessment"
            ReportAudience.CITIZEN -> "Ocean Health Report"
        }

        return buildString {
            appendLine("# OceanGuard AI — $title")
            appendLine()
            appendLine("**Survey period:** $dateRange")
            appendLine("**Sessions analysed:** $sessionCount")
            appendLine("**Generated by:** OceanGuard AI v1.0 (Template Report)")
            appendLine()
            appendLine("---")
            appendLine()
            appendLine("## Overview")
            appendLine()
            appendLine(
                "This report summarises the findings from **$sessionCount underwater debris detection " +
                "session(s)** conducted between $dateRange. A total of **$totalDebris debris item(s)** " +
                "were identified across all survey images. The mean ecosystem health score for the " +
                "surveyed area is **${String.format("%.1f", avgHealth)}/100**, classified as **$healthLabel**, " +
                "indicating ${healthDescription(avgHealth)}."
            )
            appendLine()
            appendLine(locationNote)
            appendLine()
            appendLine("---")
            appendLine()
            appendLine("## Key Findings")
            appendLine()
            appendLine("### Debris Composition")
            appendLine()
            appendLine(dominantMaterialSentence)
            appendLine()
            appendLine("**Full material breakdown:** $materialBreakdownStr")
            appendLine()
            appendLine("### Risk Assessment")
            appendLine()
            appendLine(riskSentence)
            appendLine()
            if (avgHealth < 60) {
                appendLine(
                    "> **Area of Concern:** The ecosystem health score of " +
                    "${String.format("%.1f", avgHealth)}/100 indicates significant anthropogenic stress. " +
                    "Intervention is recommended as a priority."
                )
                appendLine()
            }
            appendLine("---")
            appendLine()
            appendLine("## Recommendations")
            appendLine()
            val recs = buildRecommendations(dominantMaterial?.key, avgHealth, highRiskCount, audience)
            recs.forEachIndexed { i, rec -> appendLine("${i + 1}. $rec") }
            appendLine()
            appendLine("---")
            appendLine()
            appendLine("*This report was generated automatically by OceanGuard AI. For AI-assisted narrative " +
                "analysis, deploy the AI model to the device and regenerate.*")
        }.trimEnd()
    }

    // -----------------------------------------------------------------
    // Zone-based temporal template report
    // -----------------------------------------------------------------

    fun buildZoneTemplateReport(
        input: ZoneReportInput,
        language: String,
        audience: ReportAudience = ReportAudience.SCIENTIFIC,
    ): String {
        val totalDebris = input.sessions.sumOf { it.totalCount }
        val avgHealth = input.sessions.map { it.healthScore }.average()
        val materialMap = buildMaterialMap(input.sessions)
        val dominantMaterial = materialMap.maxByOrNull { it.value }
        val highRiskCount = countHighRisk(input.sessions)
        val dateRange = formatDateRange(input.sessions)
        val healthLabel = healthLabel(avgHealth)
        val trendLabel = trendLabel(input.trend)
        val sortedDays = input.dayGroups.sortedBy { it.date }

        val title = when (audience) {
            ReportAudience.SCIENTIFIC -> "Zone Environmental Report"
            ReportAudience.NGO_MANAGER -> "Zone Field Assessment"
            ReportAudience.CITIZEN -> "Zone Ocean Health Report"
        }

        return buildString {
            appendLine("# OceanGuard AI — $title")
            appendLine()
            appendLine("**Location:** ${input.locationName}")
            appendLine("**Survey period:** $dateRange")
            appendLine("**Sessions analysed:** ${input.sessions.size}")
            appendLine("**Survey days:** ${sortedDays.size}")
            appendLine("**Overall trend:** $trendLabel")
            appendLine("**Generated by:** OceanGuard AI v1.0 (Template Report)")
            appendLine()
            appendLine("---")
            appendLine()
            appendLine("## Zone Overview")
            appendLine()
            appendLine(
                "This report analyses **${input.sessions.size} survey session(s)** collected over " +
                "**${sortedDays.size} day(s)** at **${input.locationName}**. A total of " +
                "**$totalDebris debris item(s)** were identified. The mean health score is " +
                "**${String.format("%.1f", avgHealth)}/100** ($healthLabel), with an overall trend " +
                "classified as **$trendLabel**."
            )
            appendLine()
            appendLine("---")
            appendLine()
            appendLine("## Temporal Evolution")
            appendLine()
            appendTemporalEvolution(sortedDays)
            appendLine()
            appendTrendAssessment(sortedDays, input.trend)
            appendLine()
            appendLine("---")
            appendLine()
            appendLine("## Key Findings")
            appendLine()
            appendKeyFindings(dominantMaterial, highRiskCount, materialMap)
            appendLine()
            appendLine("---")
            appendLine()
            appendLine("## Recommendations")
            appendLine()
            val recs = buildRecommendations(dominantMaterial?.key, avgHealth, highRiskCount, audience)
            recs.forEachIndexed { i, rec -> appendLine("${i + 1}. $rec") }
            appendLine()
            appendLine("---")
            appendLine()
            appendLine("*This report was generated automatically by OceanGuard AI. For AI-assisted narrative " +
                "analysis, deploy the AI model to the device and regenerate.*")
        }.trimEnd()
    }

    // -----------------------------------------------------------------
    // No-data report
    // -----------------------------------------------------------------

    fun buildNoDataReport(language: String): String {
        val languageName = LANGUAGE_NAMES[language] ?: "English"
        return buildString {
            appendLine("# OceanGuard AI — Marine Debris Survey Report")
            appendLine()
            appendLine("**Language:** $languageName")
            appendLine()
            appendLine("No detection sessions are available to generate a report.")
            appendLine()
            appendLine("Capture at least one underwater image using the camera or gallery import, " +
                "run the debris detection analysis, and save the session. Then return here to " +
                "generate your environmental report.")
        }.trimEnd()
    }

