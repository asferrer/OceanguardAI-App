"""eval_honest.py — Evaluación post-train en sets distintos para detectar
optimismo del val Brackish (camera-leakage interno).

3 sets de eval:
  (a) marine_val   — el val global de Ultralytics. Brackish dominante. Cota
                     OPTIMISTA: el modelo ve el mismo deployment/cámara que en
                     train (Brackish es un único stream de 14h y aunque
                     train/valid del paper no comparten frames idénticos, sí
                     comparten background/iluminación/calibración).
  (b) aquarium_val — solo Aquarium-val (127 imgs). Otro setting/cámara/dataset.
                     Cota MÁS HONESTA de generalización inter-source.
  (c) suim_neg     — solo SUIM negativos (327 val). Mide el FALSE POSITIVE
                     rate del detector cuando no hay fauna real.
  (d) deepfish_val — si DeepFish está disponible: solo deepfish. OOD distinto a
                     Brackish, ojo: también es vídeo con camera-leakage interno.

Para cada set: mAP@0.5, mAP@0.5:0.95, precision/recall a un único threshold (0.25).
Para (c): no aporta mAP; solo cuenta detecciones por imagen (>0 = false positive).

Uso (post-train, cuando best.pt existe):
  python eval_honest.py --weights output/runs/train/marine_yolo26n_v1/weights/best.pt
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent


def parse_args() -> argparse.Namespace:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--weights", type=Path,
                   default=ROOT / "output" / "runs" / "train" /
                           "marine_yolo26n_v1" / "weights" / "best.pt")
    p.add_argument("--imgsz", type=int, default=416)
    p.add_argument("--batch", type=int, default=64)
    p.add_argument("--device", type=str, default="0")
    return p.parse_args()


def _write_subset_yaml(name: str, val_paths: list[Path]) -> Path:
    out_txt = ROOT / "splits" / f"eval_{name}.txt"
    out_txt.parent.mkdir(parents=True, exist_ok=True)
    out_txt.write_text(
        "\n".join(p.as_posix() for p in val_paths if p.exists()),
        encoding="utf-8",
    )
    out_yaml = ROOT / f"eval_{name}.yaml"
    out_yaml.write_text(
        f"# Auto eval slice {name} — generated by eval_honest.py\n"
        f"path: {ROOT.as_posix()}\n"
        # train must point to something non-empty for Ultralytics val mode,
        # so reuse the main train list (it's ignored in val).
        f"train: splits/train.txt\n"
        f"val: splits/eval_{name}.txt\n"
        "names:\n  0: organism\n",
        encoding="utf-8",
    )
    return out_yaml


def _list_imgs(dirs: list[Path]) -> list[Path]:
    out: list[Path] = []
    for d in dirs:
        if not d.exists():
            continue
        for p in d.rglob("*"):
            if p.is_file() and p.suffix.lower() in {".jpg", ".jpeg", ".png"}:
                out.append(p)
    return sorted(out)


def build_eval_slices() -> dict[str, Path]:
    """Materialise the val txt for each slice."""
    slices: dict[str, Path] = {}

    aquarium_val = _list_imgs([ROOT / "datasets" / "aquarium" / "images" / "valid"])
    if aquarium_val:
        slices["aquarium_val"] = _write_subset_yaml("aquarium_val", aquarium_val)

    # SUIM val (20%, deterministic) — mirror of build_merged_yaml split.
    suim_imgs = _list_imgs([ROOT / "datasets" / "suim" / "images"])
    if suim_imgs:
        import random
        rng = random.Random(43)  # build_merged_yaml seed+1
        rng.shuffle(suim_imgs)
        cut = int(len(suim_imgs) * 0.8)
        suim_val = suim_imgs[cut:]
        slices["suim_neg"] = _write_subset_yaml("suim_neg", suim_val)

    deepfish_val = _list_imgs([ROOT / "datasets" / "deepfish" / "images"])
    if deepfish_val:
        # 80/20 mirror of build_merged_yaml
        import random
        rng = random.Random(42)
        rng.shuffle(deepfish_val)
        cut = int(len(deepfish_val) * 0.8)
        slices["deepfish_val"] = _write_subset_yaml("deepfish_val", deepfish_val[cut:])

    return slices


def main() -> None:
    args = parse_args()
    if not args.weights.exists():
        raise SystemExit(f"weights not found: {args.weights}")

    from ultralytics import YOLO
    model = YOLO(str(args.weights))

    results: dict[str, dict] = {}

    # (a) marine_val (default full mix — optimistic)
    main_yaml = ROOT / "marine_1class.yaml"
    if main_yaml.exists():
        print(f"\n[main val] {main_yaml}")
        r = model.val(data=str(main_yaml), imgsz=args.imgsz, batch=args.batch,
                      device=args.device, save_json=False, plots=False, verbose=False)
        results["main_val_optimistic"] = _extract(r)

    # (b/c/d) per-source slices
    for name, yaml_path in build_eval_slices().items():
        print(f"\n[{name}] {yaml_path}")
        r = model.val(data=str(yaml_path), imgsz=args.imgsz, batch=args.batch,
                      device=args.device, save_json=False, plots=False, verbose=False)
        results[name] = _extract(r)

    out = ROOT / "output" / "_eval_honest.json"
    out.write_text(json.dumps(results, indent=2), encoding="utf-8")
    print("\n" + "=" * 70)
    print(f"{'slice':<26}  {'mAP@0.5':>9}  {'mAP@0.5:0.95':>13}  {'P':>6}  {'R':>6}")
    print("-" * 70)
    for slc, m in results.items():
        print(f"{slc:<26}  {m['map50']:>9.3f}  {m['map50_95']:>13.3f}  "
              f"{m['precision']:>6.3f}  {m['recall']:>6.3f}")
    print("=" * 70)
    print(f"\nFull results → {out}")


def _extract(r) -> dict:
    """Pull mAP / P / R out of an Ultralytics DetMetrics object."""
    # Different Ultralytics versions expose this differently; try a few.
    try:
        return {
            "map50":      float(r.box.map50),
            "map50_95":   float(r.box.map),
            "precision":  float(r.box.mp),
            "recall":     float(r.box.mr),
        }
    except AttributeError:
        return {
            "map50": float("nan"), "map50_95": float("nan"),
            "precision": float("nan"), "recall": float("nan"),
        }


if __name__ == "__main__":
    main()
